import fs from 'fs-extra'
import path from 'node:path'
import config from './config.ts'
import l10nUtil from './l10nUtil.js'
import * as Log from './log.ts'
import util from './util.js'

const update = () => {
  Log.progressStart('update branding')
  const chromeComponentsDir = path.join(config.srcDir, 'components')
  const braveComponentsDir = path.join(config.braveCoreDir, 'components')
  const chromeAppDir = path.join(config.srcDir, 'chrome', 'app')
  const braveAppDir = path.join(config.braveCoreDir, 'app')
  const braveChromiumResources = path.join(
    config.braveCoreDir,
    'build',
    'chromium',
    'resources',
  )
  const braveAppVectorIconsDir = path.join(config.braveCoreDir, 'components')
  const chromeAndroidJavaStringsTranslationsDir = path.join(
    config.srcDir,
    'chrome',
    'browser',
    'ui',
    'android',
    'strings',
    'translations',
  )
  const braveAndroidJavaStringsTranslationsDir = path.join(
    config.braveCoreDir,
    'browser',
    'ui',
    'android',
    'strings',
    'translations',
  )
  const chromeAndroidTabUiJavaStringsTranslationsDir = path.join(
    config.srcDir,
    'chrome',
    'android',
    'features',
    'tab_ui',
    'java',
    'strings',
    'translations',
  )
  const braveAndroidTabUiJavaStringsTranslationsDir = path.join(
    config.braveCoreDir,
    'android',
    'features',
    'tab_ui',
    'java',
    'strings',
    'translations',
  )

  let fileMap = new Set()
  const autoGeneratedBraveToChromiumMapping = Object.assign(
    {},
    l10nUtil.getAutoGeneratedBraveToChromiumMapping(),
  )
  // Map branded string files to chromium directories
  for (const branding of ['brave', 'brave_origin']) {
    autoGeneratedBraveToChromiumMapping[
      path.join(braveAppDir, `${branding}_strings.grd`)
    ] = path.join(chromeAppDir, `${branding}_strings.grd`)
    autoGeneratedBraveToChromiumMapping[
      path.join(braveComponentsDir, `components_${branding}_strings.grd`)
    ] = path.join(chromeComponentsDir, `components_${branding}_strings.grd`)
  }
  // Shared grdp files (only need brave versions, brave_origin includes them)
  autoGeneratedBraveToChromiumMapping[
    path.join(braveAppDir, 'settings_brave_strings.grdp')
  ] = path.join(chromeAppDir, 'settings_brave_strings.grdp')

  Object.entries(autoGeneratedBraveToChromiumMapping).forEach((mapping) =>
    fileMap.add(mapping),
  )

  // Copy xtb files for:
  // brave/app/resources/chromium_strings*.xtb
  // brave/app/resources/generated_resoruces*.xtb
  // brave/components/strings/components_chromium_strings*.xtb
  // brave/browser/ui/android/strings/translations/android_chrome_strings*.xtb
  // brave/android/features/tab_ui/java/strings/translations/android_chrome_tab_ui_strings*.xtb
  fileMap.add([
    path.join(braveAppDir, 'resources'),
    path.join(chromeAppDir, 'resources'),
  ])
  fileMap.add([
    path.join(braveComponentsDir, 'strings'),
    path.join(chromeComponentsDir, 'strings'),
  ])
  fileMap.add([
    braveAndroidJavaStringsTranslationsDir,
    chromeAndroidJavaStringsTranslationsDir,
  ])
  fileMap.add([
    braveAndroidTabUiJavaStringsTranslationsDir,
    chromeAndroidTabUiJavaStringsTranslationsDir,
  ])
  // By overwriting, we don't need to modify some grd files.
  for (const branding of ['brave', 'brave_origin']) {
    fileMap.add([
      path.join(braveAppDir, 'theme', branding),
      path.join(chromeAppDir, 'theme', branding),
    ])
    for (const scale of ['default_100_percent', 'default_200_percent']) {
      fileMap.add([
        path.join(braveAppDir, 'theme', scale, branding),
        path.join(chromeAppDir, 'theme', scale, branding),
      ])
    }
  }
  fileMap.add([path.join(braveChromiumResources), path.join(config.srcDir)])
  // Copy product_logo for version UI (about:version page).
  // product_logo_name_48.png is renamed to product_logo.png during copy.
  // Use brave_origin logos when is_brave_origin_branded is true.
  const productLogoSource = config.isBraveOriginBranded
    ? 'brave_origin'
    : 'brave'
  for (const scale of ['default_100_percent', 'default_200_percent']) {
    fileMap.add([
      path.join(
        braveAppDir,
        'theme',
        scale,
        productLogoSource,
        'product_logo_name_48.png',
      ),
      path.join(
        chromeComponentsDir,
        'resources',
        scale,
        'chromium',
        'product_logo.png',
      ),
    ])
    fileMap.add([
      path.join(
        braveAppDir,
        'theme',
        scale,
        productLogoSource,
        'product_logo_white.png',
      ),
      path.join(
        chromeComponentsDir,
        'resources',
        scale,
        'chromium',
        'product_logo_white.png',
      ),
    ])
    fileMap.add([
      path.join(
        braveAppDir,
        'theme',
        scale,
        productLogoSource,
        'product_logo_16.png',
      ),
      path.join(
        chromeComponentsDir,
        'resources',
        scale,
        'chromium',
        'favicon_product.png',
      ),
    ])
  }
  for (const branding of ['brave', 'brave_origin']) {
    fileMap.add([
      path.join(braveAppVectorIconsDir, 'vector_icons', branding),
      path.join(chromeComponentsDir, 'vector_icons', branding),
    ])

    // Copy to make our ${branding_path_product}_behaviors.cc
    fileMap.add([
      path.join(
        config.braveCoreDir,
        'chromium_src',
        'chrome',
        'installer',
        'setup',
        `${branding}_behaviors.cc`,
      ),
      path.join(
        config.srcDir,
        'chrome',
        'installer',
        'setup',
        `${branding}_behaviors.cc`,
      ),
    ])
  }
  // Replace omnibox product vector icons with the Brave or Brave Origin
  // variant. These icons are used in places like the default browser infobar;
  // upstream does not have a branding selector for them.
  //
  // Upstream's [GlowUp] series (Chromium 150) renamed `product.icon` and
  // `product_chrome_refresh.icon` to `*_old.icon` and added a new rounded
  // `chrome_product.icon` variant, so map our sources onto all three
  // destinations.
  const omniboxIconsBranding = config.isBraveOriginBranded
    ? 'brave_origin'
    : 'brave'
  /** @type {[string, string][]} */
  const omniboxIconMappings = [
    ['product.icon', 'product_old.icon'],
    ['product.icon', 'chrome_product.icon'],
    ['product_chrome_refresh.icon', 'product_chrome_refresh_old.icon'],
  ]
  for (const [srcIconName, dstIconName] of omniboxIconMappings) {
    fileMap.add([
      path.join(
        config.braveCoreDir,
        'components',
        'omnibox',
        'browser',
        'vector_icons',
        omniboxIconsBranding,
        srcIconName,
      ),
      path.join(
        config.srcDir,
        'components',
        'omnibox',
        'browser',
        'vector_icons',
        dstIconName,
      ),
    ])
  }
  // Replace webui CSS to use our fonts.
  fileMap.add([
    path.join(
      config.braveCoreDir,
      'ui',
      'webui',
      'resources',
      'css',
      'text_defaults_md.css',
    ),
    path.join(
      config.srcDir,
      'ui',
      'webui',
      'resources',
      'css',
      'text_defaults_md.css',
    ),
  ])
  // Replace chrome dark logo with our own.
  //
  // growser: upstream takes this from node_modules/@brave/leo, which is outside
  // git and rewritten by every `pnpm install`, so the lion could only ever be
  // replaced here. It is the logo the settings header shows in dark mode - not
  // product_logo_32, which is what everyone edits and which is already ours.
  fileMap.add([
    path.join(
      config.braveCoreDir,
      'app',
      'theme',
      'brave',
      'product_logo.svg',
    ),
    path.join(
      config.srcDir,
      'ui',
      'webui',
      'resources',
      'images',
      'chrome_logo_dark.svg',
    ),
  ])
  // Replace webui bookmark svg icon.
  fileMap.add([
    path.join(
      config.braveCoreDir,
      'node_modules',
      '@brave',
      'leo',
      'icons',
      'browser-bookmark-normal.svg',
    ),
    path.join(
      config.srcDir,
      'ui',
      'webui',
      'resources',
      'images',
      'icon_bookmark.svg',
    ),
  ])

  // When the channel is set, we need to copy the channel-specific files.
  let channelSpecificSourceFiles = new Set()
  for (const branding of ['brave', 'brave_origin']) {
    // Set proper branding file.
    const brandingSource = path.join(
      braveAppDir,
      'theme',
      branding,
      'BRANDING' + (config.channel ? `.${config.channel}` : ''),
    )
    const brandingDest = path.join(chromeAppDir, 'theme', branding, 'BRANDING')
    channelSpecificSourceFiles[brandingDest] = brandingSource

    // Set proper mac app icon for channel to chrome/app/theme/mac/app.icns.
    // Each channel's app icons are stored in
    // brave/app/theme/$channel/app.icns.
    // With this copying, we don't need to modify chrome/BUILD.gn for this.
    const iconSource = path.join(
      braveAppDir,
      'theme',
      branding,
      'mac',
      config.channel,
      'app.icns',
    )
    const iconDest = path.join(
      chromeAppDir,
      'theme',
      branding,
      'mac',
      'app.icns',
    )
    channelSpecificSourceFiles[iconDest] = iconSource

    // Set proper mac app asset catalog for channel to
    // chrome/app/theme/mac/Assets.car. Each channel's resource catalog is
    // stored in brave/app/theme/$channel/Assets.car. With this copying, we
    // don't need to modify chrome/BUILD.gn for this.
    const assetCatalogSource = path.join(
      braveAppDir,
      'theme',
      branding,
      'mac',
      config.channel,
      'Assets.car',
    )
    const assetCatalogDest = path.join(
      chromeAppDir,
      'theme',
      branding,
      'mac',
      'Assets.car',
    )
    channelSpecificSourceFiles[assetCatalogDest] = assetCatalogSource
  }

  for (const [source, output] of fileMap) {
    if (!fs.existsSync(source)) {
      console.warn(
        `Warning: The following file-system entry was not found for copying contents to a chromium destination: ${source}. Consider removing the entry from the file-map, or investigating whether the correct source code reference is checked out.`,
      )
      continue
    }

    let sourceFiles = []

    // get all the files if source if a directory
    if (fs.statSync(source).isDirectory()) {
      sourceFiles = util.walkSync(source)
    } else {
      sourceFiles = [source]
    }

    for (let sourceFile of sourceFiles) {
      if (path.basename(sourceFile) === 'README.md') {
        continue
      }
      const destinationFile = path.join(
        output,
        path.relative(source, sourceFile),
      )
      sourceFile = channelSpecificSourceFiles[destinationFile] || sourceFile
      if (
        !fs.existsSync(destinationFile)
        || util.calculateFileChecksum(sourceFile)
          !== util.calculateFileChecksum(destinationFile)
      ) {
        fs.copySync(sourceFile, destinationFile)
        console.log(sourceFile + ' copied to ' + destinationFile)
      }
    }
  }

  // growser: the Brave lion also lives in the Leo design system. Its glyphs are
  // in node_modules/@brave/leo/icons-skia, which is outside git and regenerated
  // by `pnpm install`, so they cannot simply be committed over. We overwrite
  // them here instead: this step runs on every build, after the install, and
  // before gn reads the icons. Sources are generated by
  // growser/brand/make-appstore-brand.py.
  const growserLeoDir = path.join(
    config.braveCoreDir,
    'components',
    'vector_icons',
    'growser_leo',
  )
  const leoSkiaDir = path.join(
    config.braveCoreDir,
    'node_modules',
    '@brave',
    'leo',
    'icons-skia',
  )
  if (fs.existsSync(growserLeoDir) && fs.existsSync(leoSkiaDir)) {
    for (const name of fs.readdirSync(growserLeoDir)) {
      const sourceFile = path.join(growserLeoDir, name)
      const destinationFile = path.join(leoSkiaDir, name)
      if (
        !fs.existsSync(destinationFile)
        || util.calculateFileChecksum(sourceFile)
          !== util.calculateFileChecksum(destinationFile)
      ) {
        fs.copySync(sourceFile, destinationFile)
        console.log(sourceFile + ' copied to ' + destinationFile)
      }
    }
  }

  // growser (#137): the product's primary colour is ours - the green of the
  // omnibox focus ring - not Brave's blue-violet. Nala's primitive primary
  // ramp is the single source both sides read (the WebUI through these CSS
  // custom properties, the native side through ui::kColorRef* in
  // brave/ui/color/brave_ref_color_mixer.cc), and it ships inside
  // node_modules, which `pnpm install` rewrites. So it is re-applied here on
  // every build, exactly like the Leo icons above.
  //
  // The values are generated by brand/make-primary-ramp.py in the growser
  // repo, which derives the ramp in OKLab - every step keeps the lightness of
  // the blue step it replaces, so no contrast ratio in the UI moves - and
  // gates all of this with `--check`.
  const primaryRampFile = path.join(
    config.braveCoreDir,
    'build',
    'growser_primary_ramp.json',
  )
  const leoTokensDir = path.join(
    config.braveCoreDir,
    'node_modules',
    '@brave',
    'leo',
    'tokens',
  )
  if (fs.existsSync(primaryRampFile) && fs.existsSync(leoTokensDir)) {
    const ramp = JSON.parse(fs.readFileSync(primaryRampFile, 'utf8'))
    // Replaced by TOKEN NAME, never by raw hex: #5b67e8 is also
    // primitive-blurple-50, a different family that stays Brave's own.
    const tokenFiles = [
      [
        'css/variables.css',
        (step) =>
          `(--leo-color-primitive-primary-${step}\\s*:\\s*)#[0-9a-fA-F]{3,8}`,
      ],
      [
        'json/styles.json',
        (step) => `("ColorPrimitivePrimary${step}"\\s*:\\s*")#[0-9a-fA-F]{3,8}`,
      ],
      [
        'android/values/colors.xml',
        (step) =>
          `(<color name="primitive_primary_${step}"[^>]*>)#[0-9a-fA-F]{3,8}`,
      ],
    ]
    for (const [name, makePattern] of tokenFiles) {
      const tokenFile = path.join(leoTokensDir, ...name.split('/'))
      if (!fs.existsSync(tokenFile)) {
        continue
      }
      const before = fs.readFileSync(tokenFile, 'utf8')
      let after = before
      for (const [step, colors] of Object.entries(ramp.steps)) {
        // 0 and 100 are pure black and white in either ramp.
        if (step === '0' || step === '100') {
          continue
        }
        after = after.replace(
          new RegExp(makePattern(step), 'g'),
          `$1${colors.to}`,
        )
      }
      if (after !== before) {
        fs.writeFileSync(tokenFile, after)
        console.log('primary ramp applied to ' + tokenFile)
      }
    }
  }

  // growser (#139): 12px is the ceiling for corners in this product, and the
  // ceiling has to be applied to the token scale, not to call sites: Leo
  // re-declares its tokens INSIDE each component's shadow root, so nothing
  // set from the page can reach them - overriding --leo-radius-full at
  // runtime leaves every toggle exactly as round as it was. Changing the file
  // is the only lever, and like the colour ramp above it has to be re-applied
  // on every build because `pnpm install` rewrites node_modules.
  //
  // Only the steps ABOVE the ceiling move; xs/s/m/l are already under it. The
  // "full" pill radius becomes 12 as well, which squares off toggles, pill
  // buttons and segmented controls - and leaves genuinely round things round,
  // because a radius larger than half the box is clamped: a 16px toggle thumb
  // with a 12px radius is still a circle.
  const radiusCap = 12
  const cappedRadii = { Xl: 16, Xxl: 24, Full: 1000 }
  if (fs.existsSync(leoTokensDir)) {
    // Each file carries the number differently, and the CSS one carries a
    // unit: a replacement that drops it writes `--leo-radius-full: 12`, which
    // is not a length and is ignored, so every corner silently keeps its old
    // shape. Hence a per-file suffix rather than one clever pattern.
    const radiusFiles = [
      ['css/variables.css', 'px',
        (name, value) => `(--leo-radius-${name.toLowerCase()}\\s*:\\s*)${value}px`],
      ['json/styles.json', '',
        (name, value) => `("Radius${name}"\\s*:\\s*)${value}`],
      ['skia/radius.h', '',
        (name, value) => `(constexpr int kRadius${name} = )${value}`],
    ]
    for (const [name, suffix, makePattern] of radiusFiles) {
      const tokenFile = path.join(leoTokensDir, ...name.split('/'))
      if (!fs.existsSync(tokenFile)) {
        continue
      }
      const before = fs.readFileSync(tokenFile, 'utf8')
      let after = before
      for (const [token, value] of Object.entries(cappedRadii)) {
        after = after.replace(
          new RegExp(makePattern(token, value), 'g'),
          `$1${radiusCap}${suffix}`,
        )
      }
      if (after !== before) {
        fs.writeFileSync(tokenFile, after)
        console.log('radius ceiling applied to ' + tokenFile)
      }
    }
  }

  if (config.targetOS === 'android') {
    let braveOverwrittenFiles = new Set()
    const removeUnlistedAndroidResources = (braveOverwrittenFiles) => {
      const suspectedDir = path.join(
        config.srcDir,
        'chrome',
        'android',
        'java',
        'res',
      )

      let untrackedChromiumFiles = util
        .runGit(
          suspectedDir,
          ['ls-files', '--others', '--exclude-standard'],
          true,
        )
        .split('\n')
      let untrackedChromiumPaths = []
      for (const untrackedChromiumFile of untrackedChromiumFiles) {
        const untrackedChromiumPath = path.join(
          suspectedDir,
          untrackedChromiumFile,
        )

        if (!fs.statSync(untrackedChromiumPath).isDirectory()) {
          untrackedChromiumPaths.push(untrackedChromiumPath)
        }
      }

      const isChildOf = (child, parent) => {
        const relative = path.relative(parent, child)
        return (
          relative && !relative.startsWith('..') && !path.isAbsolute(relative)
        )
      }

      for (const untrackedChromiumPath of untrackedChromiumPaths) {
        if (
          isChildOf(untrackedChromiumPath, suspectedDir)
          && !braveOverwrittenFiles.has(untrackedChromiumPath)
        ) {
          fs.removeSync(untrackedChromiumPath)
          console.log(`Deleted not listed file: ${untrackedChromiumPath}`)
        }
      }
    }

    let androidIconSet = ''
    if (config.channel === 'development') {
      androidIconSet = 'res_brave_default'
    } else if (config.channel === '') {
      androidIconSet = 'res_brave'
    } else if (config.channel === 'beta') {
      androidIconSet = 'res_brave_beta'
    } else if (config.channel === 'dev') {
      androidIconSet = 'res_brave_dev'
    } else if (config.channel === 'nightly') {
      androidIconSet = 'res_brave_nightly'
    }

    const androidResSource = path.join(
      config.braveCoreDir,
      'android',
      'java',
      'res',
    )
    const androidResDest = path.join(
      config.srcDir,
      'chrome',
      'android',
      'java',
      'res',
    )
    const androidFeaturesTabUiResSource = path.join(
      config.braveCoreDir,
      'android',
      'features',
      'tab_ui',
      'java',
      'res',
    )
    const androidFeaturesTabUiDest = path.join(
      config.srcDir,
      'chrome',
      'android',
      'features',
      'tab_ui',
      'java',
      'res',
    )
    const androidDownloadInternalResSource = path.join(
      config.braveCoreDir,
      'browser',
      'download',
      'internal',
      'android',
      'java',
      'res',
    )
    const androidDownloadInternalResDest = path.join(
      config.srcDir,
      'chrome',
      'browser',
      'download',
      'internal',
      'android',
      'java',
      'res',
    )
    const androidIconSource = path.join(
      braveAppDir,
      'theme',
      'brave',
      'android',
      androidIconSet,
    )
    const androidIconDest = path.join(
      config.srcDir,
      'chrome',
      'android',
      'java',
      'res_chromium',
    )
    const androidIconBaseSource = path.join(
      braveAppDir,
      'theme',
      'brave',
      'android',
      androidIconSet + '_base',
    )
    const androidIconBaseDest = path.join(
      config.srcDir,
      'chrome',
      'android',
      'java',
      'res_chromium_base',
    )

    // Mapping for copying Brave's Android resource into chromium folder.
    const copyAndroidResourceMapping = {
      [androidResSource]: [androidResDest],
      [androidFeaturesTabUiResSource]: [androidFeaturesTabUiDest],
      [androidDownloadInternalResSource]: [androidDownloadInternalResDest],
      [androidIconSource]: [androidIconDest],
      [androidIconBaseSource]: [androidIconBaseDest],
    }

    console.log('copy Android app icons and app resources')
    Object.entries(copyAndroidResourceMapping).map(
      ([sourcePath, destPaths]) => {
        let androidSourceFiles = []
        if (fs.statSync(sourcePath).isDirectory()) {
          androidSourceFiles = util.walkSync(sourcePath)
        } else {
          androidSourceFiles = [sourcePath]
        }

        for (const destPath of destPaths) {
          for (const androidSourceFile of androidSourceFiles) {
            let destinationFile = path.join(
              destPath,
              path.relative(sourcePath, androidSourceFile),
            )
            if (
              !fs.existsSync(destinationFile)
              || util.calculateFileChecksum(androidSourceFile)
                !== util.calculateFileChecksum(destinationFile)
            ) {
              fs.copySync(androidSourceFile, destinationFile)
            }
            braveOverwrittenFiles.add(destinationFile)
          }
        }
      },
    )
    removeUnlistedAndroidResources(braveOverwrittenFiles)
  }
  Log.progressFinish('update branding')
}

export default { update }
